/**
 * Pull poster frames for the Vimeo clips embedded in case studies.
 *
 *   node scripts/fetch-vimeo-posters.mjs
 *
 * The players mount only when they scroll into view, so something has to hold
 * the space and look deliberate until then. A poster does that and also gives
 * the block its true aspect ratio, which oEmbed reports alongside it -- the
 * iframe size Framer happened to use is not the video's own shape.
 *
 * Output is committed; this is not part of the build. Re-run when a clip changes.
 */
import { mkdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import sharp from 'sharp'

const CLIPS = {
  metamask: {
    '1180546666': 'showreel',
    '1180546642': 'connect-wallet',
    '1180546615': 'compatible-tokens',
    '1180546718': 'funding',
    '1181009581': 'select-assets',
  },
  dean: {
    '1190987210': 'showcase',
  },
}

const out = {}

for (const [slug, clips] of Object.entries(CLIPS)) {
  const dir = join('public/assets/case-studies', slug)
  await mkdir(dir, { recursive: true })

  for (const [id, name] of Object.entries(clips)) {
    const meta = await fetch(
      `https://vimeo.com/api/oembed.json?url=https%3A//vimeo.com/${id}&width=1200`,
    ).then((r) => r.json())

    const bytes = Buffer.from(
      await fetch(meta.thumbnail_url).then((r) => r.arrayBuffer()),
    )
    const file = `poster-${name}.webp`
    await sharp(bytes).webp({ quality: 78 }).toFile(join(dir, file))

    // Dimensions come from oEmbed, not the thumbnail: Vimeo pads posters to a
    // 16:9 crop, so a portrait clip's thumbnail lies about its shape.
    out[`${slug}/${name}`] = {
      id,
      poster: `/assets/case-studies/${slug}/${file}`,
      title: meta.title,
      width: meta.width,
      height: meta.height,
    }
    console.log(`  ${slug}/${name}  ${meta.width}x${meta.height}  "${meta.title}"`)
  }
}

const entries = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join('\n')
await writeFile(
  'content/case-studies/vimeo.generated.ts',
  `// GENERATED by scripts/fetch-vimeo-posters.mjs -- do not edit.\n` +
    `export const VIMEO = {\n${entries}\n} as const;\n\n` +
    `export type VimeoKey = keyof typeof VIMEO;\n`,
)
console.log(`\ncontent/case-studies/vimeo.generated.ts (${Object.keys(out).length} clips)`)
